let vid = 0;
function series(
  dates: string[],
  metric: Vital["metric"],
  values: number[],
  values2?: number[],
): Vital[] {
  return values.map((a, i) => ({
    id: `V${vid++}`,
    metric,
    date: dates[i],
    a,
    b: values2?.[i],
    note: "",
    status: vitalStatus(metric, a, values2?.[i]),
  }));
}
